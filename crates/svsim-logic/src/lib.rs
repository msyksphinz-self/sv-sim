//! sv-sim の 4 値 / 2 値ビットベクタの表現と演算 (IEEE 1800-2023 §6, §11)。
//!
//! 設計は `docs/milestones/M0/plan.md` §3 を参照。
//!
//! # 値の表現 (エンコーディング)
//!
//! 1 ビットを aval と bval の 2 ビットで表す。割り当ては VPI の `s_vpi_vecval` と
//! DPI の `svLogicVecVal` (Annex I, `svdpi.h`) と同じ。
//!
//! | 値 | aval | bval | [`Logic`] (u8) |
//! |---|---|---|---|
//! | 0 | 0 | 0 | 0 |
//! | 1 | 1 | 0 | 1 |
//! | Z | 0 | 1 | 2 |
//! | X | 1 | 1 | 3 |
//!
//! # 配置の契約 (plan.md §3.2)
//!
//! **適用範囲**: この契約が決めるのは **packed 値 1 個**の配置である。対象は、スカラの
//! 変数・ネット、packed 配列全体、packed 構造体全体、それに演算の一時値。
//! unpacked 配列の要素の配置はこの契約の対象外で、M1 (配列) / M3 (DPI の open array) で決める。
//!
//! 幅 `w` (ビット数、`u32`) の値のワード数を `nw = ceil(w / 64)` ([`words_for`]) とする。
//! ワードは `u64` で、ビット順はリトルエンディアン (ビット 0 = LSB = ワード 0 のビット 0)。
//!
//! | 種別 | 配置 (u64 の並び) | ワード数 |
//! |---|---|---|
//! | 4 値 (`logic` 等) | `[a_0, …, a_{nw-1}, b_0, …, b_{nw-1}]` (プレーン分離) | `2·nw` |
//! | 2 値 (`bit` 等) | `[a_0, …, a_{nw-1}]` | `nw` |
//!
//! - **正規化不変条件**: 最上位ワードの `w` ビット目以上は、両プレーンとも常に 0 にする。
//!   全演算は、正規化された入力から正規化された出力を作る。
//! - 幅 ≤ 64 も同じ規則に従う (4 値は `[a, b]` の 16 バイト、2 値は 8 バイト)。
//! - 幅 0 は「空の値」(`nw = 0`) として表現だけを許す。0 回の複製は連結の中でだけ使え、
//!   そこで無視されるため (§11.4.12.1)。連結以外の演算に幅 0 を渡すのは呼び出し側の誤り。
//! - 最大幅は [`MAX_WIDTH`] (暫定で 2^24 ビット。§6.9.1 は少なくとも 2^16 を求める)。
//! - ビュー ([`LogicRef`] 等) はプレーンが隣接していなくてもよい。
//!
//! # API の層 (plan.md §3.3)
//!
//! ```text
//!  層 1: スカラ高速パス (幅 ≤ 64)   scalar::L64 / u64             … JIT の式の仕様、インタプリタの高速パス
//!  層 2: スライスカーネル (任意幅)    LogicRef / LogicMut / BitRef / BitMut を受ける自由関数
//!  層 3: owned 値型                LogicVec / BitVec (≤ 64 はインライン)
//! ```
//!
//! - 層 1 と層 2 はヒープ確保をしない。作業領域は呼び出し側が渡す [`Scratch`] を使う。
//! - 値は符号の情報を持たない。符号で結果が変わる演算は `signed: bool` を引数に取る (§11.8.1)。
//! - 2 値と 4 値は型を分ける。2 値版のカーネルは名前の末尾に `2` を付ける。
//! - スライスカーネルは幅が揃っていることを `assert!` で検査する。自己決定のオペランド
//!   (シフト量、べき乗の指数、連結の要素、選択のインデックス) だけは別の幅を受け付ける。
//!
//! # 式の幅と符号の規則 (呼び出し側の責務、plan.md §3.6)
//!
//! ライブラリは幅と符号を決めない。呼び出し側 (sema、定数評価、MIR 生成) が次の規則を適用してから
//! カーネルを呼ぶ。
//!
//! **式のビット長** (§11.6.1):
//!
//! | 式 | 結果のビット長 | オペランドの扱い |
//! |---|---|---|
//! | サイズなしの定数 | 32 以上 (§5.7.1) | — |
//! | サイズ付きの定数 | 指定のサイズ | — |
//! | `i op j` (`op`: `+ - * / % & \| ^ ^~ ~^`) | max(L(i), L(j)) | i, j とも文脈決定 |
//! | `op i` (`op`: `+ - ~`) | L(i) | i は文脈決定 |
//! | `i op j` (`op`: `=== !== == != ==? !=? > >= < <=`) | 1 | i, j を max(L(i), L(j)) に拡張する (比較の中だけ) |
//! | `i op j` (`op`: `&& \|\| -> <->`) | 1 | i, j とも自己決定 |
//! | `op i` (`op`: `& ~& \| ~\| ^ ~^ ^~ !`) | 1 | i は自己決定 |
//! | `i op j` (`op`: `>> << >>> <<< **`) | L(i) | i は文脈決定、j は自己決定 |
//! | `i ? j : k` | max(L(j), L(k)) | i は自己決定、j と k は文脈決定 |
//! | `{i, …, j}` | L(i) + … + L(j) | すべて自己決定 |
//! | `{n{i, …, j}}` | n × (L(i) + … + L(j)) | すべて自己決定 |
//!
//! - **代入文脈**: 右辺の文脈決定のオペランドは max(右辺の幅, 左辺の幅) に拡張してから評価し、
//!   最後に左辺の幅に切り詰める (§11.6.1, §11.8.2)。
//! - **符号** (§11.8.1):
//!   - 結果が符号付きになるのは、文脈決定のオペランドがすべて符号付きのときだけ。
//!   - 比較・等価・論理演算・リダクションの結果は符号なし (1 ビット)。比較では、
//!     両オペランドが符号付きのときだけ符号付きで比べる。
//!   - 連結、複製、ビット選択、部分選択の結果は常に符号なし。
//!   - シフトとべき乗の結果の符号は左オペランドで決まる。
//!   - `?:` の結果は、j と k の両方が符号付きのときだけ符号付き。
//!   - 自己決定のオペランドは自分の型のまま評価する。
//! - **評価の手順** (§11.8.2): 式全体の型と幅を先に決め、文脈決定のオペランドをその幅に拡張してから
//!   評価する。拡張は、拡張する前のオペランドの符号で行う。
//! - `$signed` / `$unsigned` (§11.7) は値を変えない。ライブラリでは何もしない。
//!
//! # 2 値と 4 値の混在 (plan.md §3.5.1)
//!
//! 自己決定のオペランド (シフト量、べき乗の指数、選択のインデックス、`?:` の条件) は、データ側が
//! 2 値でも X/Z を持ちうる。例: `bit [7:0] b; logic [2:0] s = 3'bx;` のとき `b << s` は X になる。
//!
//! 1. **評価の値域**: オペランドのどれか (自己決定のものを含む) が 4 値型なら、その演算は
//!    4 値カーネルで評価し、結果の値も 4 値で持つ。
//! 2. **結果の型**: 幅と符号は規格どおりに決める (例: シフトは左オペランドから。§11.6.1, §11.8.1)。
//!    結果の値は 4 値の一時値で持つ。
//! 3. **2 値化の時期**: X/Z → 0 の変換 (§6.11.2) は、2 値型の変数への代入時 (および 2 値型の
//!    引数・ポートへの受け渡し時) にだけ行う。式の途中では X はそのまま伝わる。
//! 4. sema は自己決定の 4 値オペランドを勝手に 2 値化しない。
//! 5. **例外: 選択**。2 値のベクタを X/Z のインデックスで読んだ値は 2 値の 0 (§11.5.1)。範囲外も同じ。
//!
//! 混在カーネル (`shl_bits`、`pow_bits`、`cond_merge_bits`、`get_slice2` 等) は、
//! 「`from_two_state` してから 4 値カーネル」と同じ結果を、一時値を作らずに計算する。
//!
//! # モジュール
//!
